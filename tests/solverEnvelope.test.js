// Solver feasibility envelope — a permanent regression guard.
//
// WHY THIS EXISTS
//
// solvePaddle silently rejected 40-65% of realistic shot requests for a long
// time and nothing noticed, for three compounding reasons:
//   1. On rejection aiFSM retries a safe (0, 0.7, 4.0 m/s, spin 0) target, so
//      the AI kept playing — just slowly, and to the middle.
//   2. aiFSM feeds the POST-fallback result to failureHandler, so a rescued
//      shot resets the infeasibility counter and the failure rate never
//      surfaced in telemetry.
//   3. No test measured feasibility at all.
//
// The underlying defects were a spin moment-arm unit error (paddle face radius
// used where the ball's no-slip arm belonged, 3.15x too large) and the spin
// face-tilt invalidating the ballistic solution it was applied on top of.
//
// These tests measure the envelope directly, so a regression shows up as a
// number rather than as "the AI feels passive".
//
// Contacts are generated by running the REAL interception rollout on plausible
// player shots — the same path the game uses — so the geometry is realistic
// rather than uniformly random.

const THREE = require('three');

jest.mock('../js/scene/models.js', () => {
  const T = require('three');
  return {
    tableBox: new T.Box3(
      new T.Vector3(-0.7625, -0.001, -1.37),
      new T.Vector3(0.7625, 0.001, 1.37),
    ),
    tableSurfaceY: 0,
    ballRadius: 0.02,
    ballModel: null,
  };
});
jest.mock('../js/physics/ball.js', () => {
  const T = require('three');
  return { ballVelocity: new T.Vector3(), ballAngularVelocity: new T.Vector3() };
});

import { rolloutForAIInterception } from '../js/ai/shotAdapter.js';
import { solvePaddle, SOLVER_REASONS, MAX_PADDLE_SPEED_MPS } from '../js/ai/paddleSolver.js';

function v(x, y, z) { return new THREE.Vector3(x, y, z); }

function makeEnv() {
  return {
    tableSurfaceY: 0,
    tableCenterZ: 0,
    ballRadius: 0.02,
    tableBox: new THREE.Box3(v(-0.7625, -0.001, -1.37), v(0.7625, 0.001, 1.37)),
  };
}

function mulberry32(seed) {
  let s = seed >>> 0;
  return function rng() {
    s = (s + 0x6D2B79F5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// Plausible player shots → real AI interception states.
function realisticContacts(n, rng) {
  const out = [];
  let guard = 0;
  while (out.length < n && guard++ < n * 30) {
    const r = rolloutForAIInterception(
      v((rng() - 0.5) * 1.0, 0.25 + rng() * 0.35, 0.6 + rng() * 0.6),
      v((rng() - 0.5) * 1.5, 0.3 + rng() * 1.6, -(4 + rng() * 6)),
      v((rng() - 0.5) * 120, 0, 0),
    );
    if (r) out.push(r);
  }
  return out;
}

function solveAt(contacts, { targetZ, targetSpeed, targetSpin, difficulty }) {
  const env = makeEnv();
  let feasible = 0;
  const reasons = {};
  for (const c of contacts) {
    const r = solvePaddle({
      targetX: 0, targetZ, targetSpeed, targetSpin,
      contactPos: v(c.contactPoint.x, c.contactPoint.y, c.contactPoint.z),
      contactVel: v(c.contactVelocity.x, c.contactVelocity.y, c.contactVelocity.z),
      contactSpin: v(c.contactSpin.x, c.contactSpin.y, c.contactSpin.z),
      difficulty, env,
    });
    if (r.feasible) feasible += 1;
    else reasons[r.reason] = (reasons[r.reason] || 0) + 1;
  }
  return { rate: feasible / contacts.length, reasons };
}

const CONTACTS = realisticContacts(120, mulberry32(11));

describe('solver envelope', () => {
  test('the contact generator produced a usable sample', () => {
    expect(CONTACTS.length).toBe(120);
  });

  // The headline guard. Before the fixes this was ~0% at 16 m/s at EVERY
  // depth, which is what made a ~13 m/s "physics ceiling" look real.
  test('mid-depth targets are reachable across the full speed range', () => {
    for (const targetSpeed of [6, 10, 14, 18, 22]) {
      const { rate } = solveAt(CONTACTS, {
        targetZ: 0.7, targetSpeed, targetSpin: 30, difficulty: 'pro',
      });
      expect(rate).toBeGreaterThan(0.9);
    }
  });

  test('rally-pace shots are reachable at every depth', () => {
    for (const targetZ of [0.4, 0.7, 1.0, 1.3]) {
      const { rate } = solveAt(CONTACTS, {
        targetZ, targetSpeed: 10, targetSpin: 30, difficulty: 'pro',
      });
      expect(rate).toBeGreaterThan(0.9);
    }
  });

  // Deep + fast is genuinely hard — a fast ball to the far edge runs out of
  // table. That constraint is REAL (it is true of actual table tennis), so we
  // pin it as expected behaviour rather than a defect. It is also why the
  // engines couple shot pace to target depth.
  test('deep targets do get harder at high pace, as physics requires', () => {
    const slow = solveAt(CONTACTS, { targetZ: 1.3, targetSpeed: 8, targetSpin: 30, difficulty: 'pro' });
    const fast = solveAt(CONTACTS, { targetZ: 1.3, targetSpeed: 22, targetSpin: 30, difficulty: 'pro' });
    expect(slow.rate).toBeGreaterThan(0.9);
    expect(fast.rate).toBeLessThan(slow.rate);
  });

  // The spin moment-arm bug made this a hard ceiling: |spin| above
  // maxPaddleSpeed / (0.09 * 2π) was rejected regardless of geometry —
  // 8.8 rps at beginner, 19.5 at intermediate, 23 at pro.
  //
  // Spin values are physical rps (spin-economy rescale ×2.5). Backspin's
  // measured shoulder at THIS cell's geometry (z 0.9 at 9 m/s) sits near
  // -45: heavier backspin at pace to depth floats long — the same
  // "pace AT DEPTH" constraint the speed table above documents, now on the
  // spin axis. The heavy end is asserted separately below at the geometry
  // it is actually played at.
  test('spin no longer has a geometry-independent ceiling', () => {
    for (const targetSpin of [-45, -25, 0, 25, 40, 55, 64]) {
      const { rate } = solveAt(CONTACTS, {
        targetZ: 0.9, targetSpeed: 9, targetSpin, difficulty: 'pro',
      });
      expect(rate).toBeGreaterThan(0.7);
    }
  });

  test('heavy chop backspin is deliverable at chop geometry', () => {
    // Pro chop profile: ~-55 rps at 5-7 m/s to short/mid targets. Measured
    // 98-100% feasible at z 0.6 / 7 m/s (vs ~58% if aimed deep at pace —
    // which is why the chop profile pairs heavy spin with slow short balls).
    const { rate } = solveAt(CONTACTS, {
      targetZ: 0.6, targetSpeed: 7, targetSpin: -52, difficulty: 'pro',
    });
    expect(rate).toBeGreaterThan(0.9);
  });

  test('no shot is rejected on the paddle-speed cap at rally pace', () => {
    // PADDLE_SPEED_CAP rejections were ~35% of all intermediate shots. At
    // sane speeds and spins the cap should never be the binding constraint.
    for (const targetSpin of [-50, 0, 50]) {
      const { reasons } = solveAt(CONTACTS, {
        targetZ: 0.9, targetSpeed: 9, targetSpin, difficulty: 'intermediate',
      });
      expect(reasons[SOLVER_REASONS.PADDLE_SPEED_CAP] || 0).toBe(0);
    }
  });

  test('every tier can execute its own rally pace', () => {
    // A tier whose own profile speeds are infeasible plays the safe fallback
    // instead, i.e. slower than the tier below it.
    for (const [difficulty, speed] of [['beginner', 5], ['intermediate', 9], ['pro', 11]]) {
      const { rate } = solveAt(CONTACTS, {
        targetZ: 0.8, targetSpeed: speed, targetSpin: 25, difficulty,
      });
      expect(rate).toBeGreaterThan(0.8);
    }
  });

  test('strike caps are not the binding constraint for any tier at its own pace', () => {
    for (const [difficulty, speed] of [['beginner', 5], ['intermediate', 9], ['pro', 11]]) {
      const { reasons } = solveAt(CONTACTS, {
        targetZ: 0.8, targetSpeed: speed, targetSpin: 25, difficulty,
      });
      const capped = (reasons[SOLVER_REASONS.PADDLE_SPEED_CAP] || 0)
        + (reasons[SOLVER_REASONS.CORRECTED_SPEED_CAP] || 0);
      expect(capped / CONTACTS.length).toBeLessThan(0.05);
      expect(MAX_PADDLE_SPEED_MPS[difficulty]).toBeGreaterThan(0);
    }
  });
});

// The measurement that actually matters: real engine output, fed to the real
// solver. Everything above sweeps a grid; this asks whether the shots the AI
// genuinely chooses can be executed.
//
// A low rate here does not stall the AI — aiFSM silently substitutes a safe
// 4.0 m/s centre ball — which is exactly why it needs a test. The symptom is
// "the AI feels passive", which no assertion would otherwise catch.
describe('end-to-end: engine requests are executable', () => {
  const { createBeginnerEngine } = require('../js/ai/engines/beginner.js');
  const { createIntermediateEngine } = require('../js/ai/engines/intermediate.js');
  const { createProEngine } = require('../js/ai/engines/pro.js');
  const { ShotHistory } = require('../js/ai/shotHistory.js');

  const FACTORIES = {
    beginner: createBeginnerEngine,
    intermediate: createIntermediateEngine,
    pro: createProEngine,
  };

  function runTier(difficulty) {
    const env = makeEnv();
    const engine = FACTORIES[difficulty]({ rng: mulberry32(5) });
    const history = new ShotHistory();
    let feasible = 0;
    const speeds = [];
    for (const c of CONTACTS) {
      const [tx, tz, speed, spin] = engine.computeTarget(history, {});
      speeds.push(speed);
      const r = solvePaddle({
        targetX: tx, targetZ: tz, targetSpeed: speed, targetSpin: spin,
        contactPos: v(c.contactPoint.x, c.contactPoint.y, c.contactPoint.z),
        contactVel: v(c.contactVelocity.x, c.contactVelocity.y, c.contactVelocity.z),
        contactSpin: v(c.contactSpin.x, c.contactSpin.y, c.contactSpin.z),
        difficulty, env,
      });
      if (r.feasible) feasible += 1;
      engine.ingestShot(null, null);
    }
    speeds.sort((a, b) => a - b);
    return {
      rate: feasible / CONTACTS.length,
      median: speeds[Math.floor(speeds.length / 2)],
    };
  }

  test.each(['beginner', 'intermediate', 'pro'])(
    '%s: most of what the engine asks for is executable',
    (difficulty) => {
      expect(runTier(difficulty).rate).toBeGreaterThan(0.75);
    },
  );

  test('median rally pace rises with tier', () => {
    const b = runTier('beginner').median;
    const i = runTier('intermediate').median;
    const p = runTier('pro').median;
    expect(i).toBeGreaterThan(b);
    expect(p).toBeGreaterThan(i);
  });
});

describe('solver accuracy', () => {
  test('feasible solves land close to target, without a systematic bias', () => {
    const env = makeEnv();
    const errors = [];
    let signedRange = 0;
    let n = 0;
    for (const c of CONTACTS) {
      const targetZ = 0.9;
      const r = solvePaddle({
        targetX: 0, targetZ, targetSpeed: 9, targetSpin: 25,
        contactPos: v(c.contactPoint.x, c.contactPoint.y, c.contactPoint.z),
        contactVel: v(c.contactVelocity.x, c.contactVelocity.y, c.contactVelocity.z),
        contactSpin: v(c.contactSpin.x, c.contactSpin.y, c.contactSpin.z),
        difficulty: 'pro', env,
      });
      if (!r.feasible || !r.predictedLanding) continue;
      errors.push(r.landingError);
      // Signed range error: did it land long or short of the target line?
      const distTarget = Math.hypot(0 - c.contactPoint.x, targetZ - c.contactPoint.z);
      const distActual = Math.hypot(
        r.predictedLanding.x - c.contactPoint.x,
        r.predictedLanding.z - c.contactPoint.z,
      );
      signedRange += distActual - distTarget;
      n += 1;
    }
    expect(n).toBeGreaterThan(50);
    const mean = errors.reduce((a, b) => a + b, 0) / errors.length;
    expect(mean).toBeLessThanOrEqual(0.15);
    // Unbiased: the mean SIGNED range error should sit near zero. A solver that
    // is systematically short (as the single-shot `ratio` correction was) still
    // passes an absolute-error check while consistently under-hitting.
    expect(Math.abs(signedRange / n)).toBeLessThan(0.08);
  });
});
